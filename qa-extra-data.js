  "answer": "CEO判断试点医院的PLS项目是否成功，需要同时回答三个问题：患者是否真正获益，医院能否稳定交付，业务能否持续增长。建议用六项核心KPI，加上医疗质量底线共同判断。单独达到营收或转化率目标，不能说明PLS项目已经成功。\n\n第一，个性化视觉目标达成率。术前通过IDEAL记录患者最核心的1—3项生活视觉目标，例如阅读、电脑工作或夜间驾驶，并由医生确认合理预期；术后在预定时间逐项核对，统计主要目标达成比例。应同时了解视觉质量、眩光与光晕等困扰，以及必要的客观检查结果，不能只用视力表数字代表患者获益。\n\n第二，满意度与再选率。满意度反映患者对诊疗服务和全程体验的评价；再选率回答“如果重新选择，是否仍愿意接受同一治疗方案”。是否再次选择同一家医院可作为独立问题，不能混为一个指标。应固定问法、评价尺度和随访时间，保留负向反馈，并同时报告应随访人数、实际回答人数和覆盖率。\n\n第三，关键流程与随访闭环率。抽查需求记录、医生方案、患者理解确认、岗位交接及随访是否按医院标准完成，观察不同人员接手时能否持续执行。还要单列患者困扰的按期处置闭环率：在约定期限内完成专业评估、处置或明确后续计划，并向患者反馈。提醒过、联系过或填完表格，不等于问题已经解决。\n\n第四，医学适合患者的分层转化率。分别统计完成评估、完成方案沟通、选择方案和完成手术的比例，明确每一层的分母、时间窗及暂缓或未选择的原因。白内障与CLE应分开统计。转化改善应来自真实需求识别、充分理解和服务改善，患者自主选择基础方案或暂缓手术也可能是合理结果。\n\n第五，全自费有效营收。白内障与CLE分开，按院区、术式和方案统计已完成服务对应的收入，扣除退费，同时看手术量与例均收入，避免把预收款直接当成项目成果。与试点前可比基线对照，结合季节、患者结构、价格及获客投入解释变化，不能把全部增长直接归因于PLS。\n\n第六，项目贡献利润。由财务在启动前统一口径，以相关收入扣除约定成本，纳入耗材、获客、增加的服务与随访成本，以及退费和补救支出。试点期应明确一次性建设投入及阶段目标，判断合理周期内的可持续性，不能只看收入增加而忽略交付成本。\n\n医疗质量是上述指标成立的前提。由医院医疗团队制定并持续监测临床结果、并发症、非计划再次干预等指标，审查适应证与知情决策，对质量问题及时处置并复盘。白内障与CLE需要分别确定适用标准，不能用经营结果抵消质量问题，也不能因少量病例中未发生严重并发症就认定长期安全已经得到证明。ICHOM白内障结局框架同时关注患者报告的视觉功能、视力、屈光结果和并发症，可作为白内障临床指标设计的参考，不能直接替代CLE标准。\n\n“达到多少算成功”应在试点启动前约定。先测本院基线，再设定患者获益、服务交付和经营结果的阶段目标，统一定义、分母、观察时间与数据来源。不同基础的院区可以有不同改善目标，不宜直接统一设定满意度95%或转化率50%等缺乏依据的成功线。所有比例都要显示样本量和随访覆盖率，按患者或按眼统计应事先明确，不能将两眼当成两位独立患者；转化率不宜作为一线人员的单一考核指标。\n\n90天试点初步成功，是指流程已跑通、数据可信，已到随访时间的患者结果和阶段经营目标达到约定要求，且医疗团队确认质量表现可接受、没有未处置的重大质量问题。第90天尚未完成规定随访的患者仍需继续追踪，不能提前计入已达标结果。\n\n具备集团推广条件，还需要在后续连续复盘中保持达标，多家不同基础的院区能够重复实现，医院团队能够自主运行，并形成明确的人员、流程、工具和成本标准。最终判断是：在医疗质量有保障的前提下，患者觉得值得，医院交付稳定，经营增长可持续，而且这些结果能够在不同院区重复做到。",
